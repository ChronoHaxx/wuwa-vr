// Original site tooling, MIT. The GitHub README and the old player-doc paths point at
// the website, which is the one place player docs are written. Both are generated from
// the same inputs as the site (dev/site-status.json, dev/i18n/home/en.json and
// site/languages/en.js), so they cannot drift from it; dev/check-site-sync.cjs fails
// a release whose committed copies differ.
//   node dev/build-readme.cjs   (dev/build-home.cjs runs it last)
const fs = require('node:fs'), path = require('node:path');
const L = require('./site-layout.cjs');
const root = path.resolve(__dirname, '..');
const site = 'https://chronohaxx.github.io/wuwa-vr/';
const note = '<!-- Generated by dev/build-readme.cjs from the website sources. Edit those, then run node dev/build-site.cjs --launcher-release. -->';

function readme() {
  const status = L.status(), home = JSON.parse(fs.readFileSync(path.join(__dirname, 'i18n/home/en.json'), 'utf8'));
  const strings = require(path.join(root, 'site/languages/en.js'));
  const release = `${L.repo}/releases/tag/${status.tag}`, asset = name => `${L.repo}/releases/download/${status.tag}/${name}`;
  const languages = L.languages.filter(([code]) => code !== 'en').map(([code, name]) => `[${name}](${site}l/${code}.html)`).join(' · ');
  return `${note}
# WuWa VR

${home.hero.lede}

**[Download WuWa-VR-Setup.exe](${asset(status.installer)})** · ${status.appVersion} beta · Wuthering Waves ${status.game} · Windows 10/11, 64-bit

**[Website](${site})**: setup, the [player guide](${site}guide.html), [controls](${site}guide.html#controls), [troubleshooting](${site}guide.html#recovery) and [videos](${site}#watch). In ten languages: ${languages}.

Run the installer, open **WuWa VR**, select **Install VR**, then **Launch in VR**. Found a problem? [Report an issue](${L.repo}/issues) and attach the zip from **Troubleshooting → Save a problem report**.

**${strings.riskTitle}** ${strings.riskText} [Account risk](${site}risk.html).

## Source

- [Desktop launcher](launcher/native/): MIT, [licence](launcher/native/LICENSE.txt).
- [Mod source, Lua and translations](mod/): our changes and pinned patches, [build instructions](mod/BUILD.md). Upstream and community components keep their own licences; the combined mod is not under one open-source licence ([component licences](LICENSE.md)).
- [Release ${status.appVersion}](${release}): installer, [portable ZIP](${asset('WuWa-VR-Launcher.zip')}) (advanced fallback), matching source and SHA-256 checksums.
- Website and player docs: \`dev/i18n/\` (ten languages), \`dev/site-content/\` (English reference), built into \`site/\` by \`node dev/build-site.cjs --launcher-release\`. [Contributing](CONTRIBUTING.md).

Built on community work: praydog and the UEVR contributors, mirudo2 (polar), SannpoKun, Indath, endlessfalls, Elliott Tate and others. [Credits](CREDITS.md). Free fan project, not affiliated with Kuro Games; [optional Ko-fi support](https://ko-fi.com/chronohax).
`;
}

// The old player docs keep their paths for existing links and point at the website.
const pointers = {
  'START-HERE.md': ['Start playing', 'guide.html', 'the player guide (ten languages): install, launch, updates, controls and recovery'],
  'CONTROLS.md': ['WuWa VR controls', 'reference.html#controls', 'every shortcut with a search; the everyday controls are also in the player guide'],
  'COMFORT.md': ['Put the view and HUD where you want them', 'reference.html#comfort', 'HUD, camera and comfort settings'],
  'TROUBLESHOOTING.md': ['Known issues and recovery', 'reference.html#recovery', 'known issues and what to do'],
  'RISK.md': ['Before you use WuWa VR', 'risk.html', 'the account-risk notice and disclaimer']
};
const pointer = ([title, page, what]) => `${note}
# ${title}

This page moved to the website: [${what}](${site}${page}).

The website is the one place player docs are written. Their sources are in
\`dev/i18n/\` and \`dev/site-content/\`.
`;

function outputs() {
  const files = {'README.md': readme()};
  for (const [name, spec] of Object.entries(pointers)) files['docs/' + name] = pointer(spec);
  return files;
}
function build() {
  const files = outputs();
  for (const [name, text] of Object.entries(files)) fs.writeFileSync(path.join(root, name), text);
  return Object.keys(files).length + ' README and docs pointer files';
}
module.exports = {build, outputs};
if (require.main === module) console.log('Wrote ' + build() + '.');
