using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Threading;
using WuWaVR.Manager;

// Troubleshooting > Recovery > Remove old versions (OldVersions.cs): what it removes and what it keeps.
public static class OldVersionsTests
{
    static int count;
    static void Check(bool value, string label) { if (!value) throw new Exception("Old versions: " + label); count++; Console.WriteLine("PASS OLD VERSIONS " + label); }
    sealed class Fixture
    {
        public string Manager;
        public PackageStore Store;
        public readonly Dictionary<string, Installed> Items = new Dictionary<string, Installed>();
        public Fixture(string root)
        {
            Manager = Path.Combine(root, Guid.NewGuid().ToString("N"), "manager");
            Store = new PackageStore(Manager);
            Directory.CreateDirectory(Store.Cache);
            int n = 0;
            foreach (string name in new[] { "old-one", "old-two", "runtime", "previous", "current" })
            {
                // A complete download named by its digest, and the version extracted from it.
                string temp = Path.Combine(Store.Cache, "temp"); File.WriteAllText(temp, "inert ZIP " + name);
                string sha = RepoClient.Hash(temp); File.Move(temp, Path.Combine(Store.Cache, sha + ".zip"));
                var release = new Release { id = "candidate-old-" + name, buildId = "fixture", gameVersion = "3.7", channel = "candidate",
                    created = DateTime.UtcNow.ToString("o"), size = 1, sha256 = sha, displayName = "Test " + name };
                var item = new Installed { release = release, folder = "candidate-old-" + name + "-abc", installedUtc = DateTime.UtcNow.AddMinutes(n++).ToString("o") };
                Store.State.installed.Add(item); Items[name] = item;
                string folder = Store.Folder(item);
                string runtime = Path.Combine(folder, "app", "runtime", "Wuthering Waves UEVR - " + name);
                Directory.CreateDirectory(runtime);
                string dll = Path.Combine(runtime, "UEVRBackend.dll"); File.WriteAllText(dll, "inert backend " + name);
                File.WriteAllText(Path.Combine(runtime, "Custom_UEVR_Injector.txt"), "generated by the injector");
                Json.Save(Path.Combine(folder, "manifest.json"), new { packageId = "wuwa-vr-launcher-" + release.id,
                    files = new Dictionary<string, string> { { "app/runtime/Wuthering Waves UEVR - " + name + "/UEVRBackend.dll", RepoClient.Hash(dll) } } });
            }
            Store.State.selected = Items["current"].folder; Store.State.previous = Items["previous"].folder; Store.Save();
        }
        public string Folder(string name) { return Store.Folder(Items[name]); }
        public string Zip(string name) { return Path.Combine(Store.Cache, Items[name].release.sha256 + ".zip"); }
    }
    public static void Run(string testRoot)
    {
        count = 0; string root = Path.Combine(testRoot, "old-versions-" + Guid.NewGuid().ToString("N")); Directory.CreateDirectory(root);
        var f = new Fixture(root);
        // A player's own file inside an old version, a folder an earlier removal left with only the injector's
        // file, a folder with someone's notes, a stray file in the cache and an unfinished download.
        File.WriteAllText(Path.Combine(f.Folder("old-two"), "my-notes.txt"), "player notes");
        string leftover = Path.Combine(f.Store.Root, "versions", "candidate-20261003-left-behind-123");
        Directory.CreateDirectory(Path.Combine(leftover, "app", "runtime", "Wuthering Waves UEVR - left"));
        File.WriteAllText(Path.Combine(leftover, "app", "runtime", "Wuthering Waves UEVR - left", "Custom_UEVR_Injector.txt"), "generated");
        string personal = Path.Combine(f.Store.Root, "versions", "someone-else-456"); Directory.CreateDirectory(personal);
        File.WriteAllText(Path.Combine(personal, "keep.txt"), "not ours");
        string stray = Path.Combine(f.Store.Cache, "readme.zip"); File.WriteAllText(stray, "not a digest name");
        string partial = Path.Combine(f.Store.Cache, new string('b', 64) + ".zip.partial"); File.WriteAllText(partial, "resumable");
        string runtimeManifest = Path.Combine(f.Folder("runtime"), "app", "openxr", "runtime.json");

        var plan = OldVersions.Find(f.Store, new[] { runtimeManifest });
        Check(plan.Versions.Select(x => x.folder).OrderBy(x => x).SequenceEqual(new[] { f.Items["old-one"].folder, f.Items["old-two"].folder }),
            "only versions neither in use, previous nor used by the OpenXR runtime are planned");
        Check(plan.Kept.Count == 3 && plan.Leftovers.SequenceEqual(new[] { leftover }) &&
            plan.Downloads.OrderBy(x => x).SequenceEqual(new[] { f.Zip("old-one"), f.Zip("old-two") }.OrderBy(x => x)) && plan.Bytes > 0,
            "a generated-only leftover and the old versions' downloads are planned; the player's folder and odd files are not");

        var result = OldVersions.Remove(f.Store, plan, CancellationToken.None);
        var saved = new PackageStore(f.Manager).State;
        Check(result.Removed == 2 && result.Retained.Count == 0 && result.Freed > 0, "two versions removed and the space counted");
        Check(!Directory.Exists(f.Folder("old-one")) && !Directory.Exists(leftover), "removed folders, generated files and empty folders are gone");
        Check(File.Exists(Path.Combine(f.Folder("old-two"), "my-notes.txt")) &&
            Directory.EnumerateFiles(f.Folder("old-two"), "*", SearchOption.AllDirectories).Count() == 1, "a player's file in an old version stays, alone");
        Check(File.Exists(Path.Combine(personal, "keep.txt")) && File.Exists(stray) && File.Exists(partial), "unknown folders, odd cache files and unfinished downloads stay");
        Check(!File.Exists(f.Zip("old-one")) && !File.Exists(f.Zip("old-two")) &&
            File.Exists(f.Zip("current")) && File.Exists(f.Zip("previous")) && File.Exists(f.Zip("runtime")), "only the removed versions' downloads are deleted");
        Check(saved.selected == f.Items["current"].folder && saved.previous == f.Items["previous"].folder && saved.installed.Count == 3 &&
            Directory.Exists(f.Folder("current")) && Directory.Exists(f.Folder("previous")) && Directory.Exists(f.Folder("runtime")),
            "the version in use, the previous one and the runtime's stay installed and selected");
        Check(OldVersions.Find(f.Store, new[] { runtimeManifest }).Empty, "a second run finds nothing");
        Check(OldVersions.Find(f.Store, null).Versions.Count == 0, "unreadable OpenXR registration keeps every version");

        var g = new Fixture(root); g.Store.State.selected = null; g.Store.State.previous = null; g.Store.Save();
        var none = OldVersions.Find(g.Store, new string[0]);
        Check(none.Kept.Count == 1 && none.Kept[0].folder == g.Items["current"].folder && none.Versions.Count == 4, "with nothing selected the newest install stays");
        Console.WriteLine(count + " old-versions checks passed.");
    }
}
